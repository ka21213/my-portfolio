import "dotenv/config";
import mongoose from "mongoose";
import config from "./config/config.js";
import User from "./server/models/user.model.js";

async function createTestUser() {
  try {
    await mongoose.connect(config.mongoUri, {
      dbName: "Portfolio",
    });

    const email = "test.portfolio@example.com";
    const password = "TestPass123!";

    // Find the test user if it already exists.
    let user = await User.findOne({ email });

    if (!user) {
      user = new User();
      user.email = email;
    }

    // Assigning password triggers your model's virtual setter.
    user.name = "Portfolio Test User";
    user.password = password;

    await user.save();

    console.log("Test user created or updated successfully!");
    console.log("Email: test.portfolio@example.com");
    console.log("Password: TestPass123!");
    console.log("Password hash and salt generated by your User model.");
  } catch (error) {
    console.error("Could not create test user:", error.message);
  } finally {
    await mongoose.disconnect();
  }
}

createTestUser();
